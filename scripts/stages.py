#!/usr/bin/env python3
"""Generate .github/workflows/build-target.yml, the chain of resumable build stages.

GitHub-hosted jobs stop after six hours, so a full Chromium build runs as a fixed
chain of stage jobs. Each stage resumes the previous stage's ninja tree and the
chain stops at the first stage that finishes the build.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
WORKFLOW = ROOT / ".github" / "workflows" / "build-target.yml"
STAGES = 16
RUNNERS = {
    "linux-x64": "ubuntu-24.04", "linux-arm64": "ubuntu-24.04",
    "windows-x64": "windows-2025", "windows-arm64": "windows-2025",
    "macos-x64": "macos-15-intel", "macos-arm64": "macos-15-intel",
}


def render():
    runners = ",".join(f'"{target}":"{runner}"' for target, runner in RUNNERS.items())
    lines = [
        "# Generated by scripts/stages.py; edit that script and regenerate.",
        "name: Build target",
        "on:",
        "  workflow_call:",
        "    inputs:",
        "      target:",
        "        type: string",
        "        required: true",
        "      stage-minutes:",
        "        type: string",
        "        default: \"295\"",
        "permissions:",
        "  contents: read",
        "jobs:",
    ]
    for stage in range(1, STAGES + 1):
        lines += [f"  s{stage}:", f"    name: stage {stage}"]
        if stage > 1:
            lines += [f"    needs: s{stage - 1}",
                      f"    if: ${{{{ !cancelled() && needs.s{stage - 1}.outputs.complete == 'false' }}}}"]
        lines += [
            f"    runs-on: ${{{{ fromJSON('{{{runners}}}')[inputs.target] }}}}",
            "    timeout-minutes: 355",
            "    outputs:",
            "      complete: ${{ steps.stage.outputs.complete }}",
            "    steps:",
            "      - uses: actions/checkout@d23441a48e516b6c34aea4fa41551a30e30af803 # v6",
            "      - id: stage",
            "        uses: ./.github/actions/stage",
            "        with:",
            "          target: ${{ inputs.target }}",
            f"          stage: \"{stage}\"",
            f"          previous: \"{stage - 1 if stage > 1 else ''}\"",
            "          budget-minutes: ${{ inputs.stage-minutes }}",
        ]
    needs = ", ".join(f"s{stage}" for stage in range(1, STAGES + 1))
    lines += [
        "  verdict:",
        f"    needs: [{needs}]",
        "    if: ${{ always() }}",
        "    runs-on: ubuntu-latest",
        "    steps:",
        "      - name: Require a finished build",
        "        env:",
        "          NEEDS: ${{ toJSON(needs) }}",
        "        run: |",
        "          echo \"$NEEDS\" | jq -e '[.[] | select(.result == \"success\" and .outputs.complete == \"true\")] | length == 1'",
    ]
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    WORKFLOW.write_text(render(), encoding="utf-8", newline="\n")
